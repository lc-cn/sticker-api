#!/usr/bin/env node
// Copy A's pure contract libraries (verbatim, per CONTRACT.md) + schemas + default config + test
// fixture into vendor/sticker-assets. Read-only with respect to A. Usage:
//   node scripts/vendor-assets-contract.mjs [/path/to/sticker-assets]
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const src = path.resolve(process.argv[2] ?? '../sticker-assets');
const dst = path.resolve('vendor/sticker-assets');
// runtime: canonical hash image indexer jsonschema strip time tokenize urls; tests only: repo validator
const LIBS = ['canonical', 'commit-plan', 'hash', 'image', 'indexer', 'jsonschema', 'repo', 'search', 'strip', 'time', 'tokenize', 'urls', 'validator'];
fs.rmSync(dst, { recursive: true, force: true });
fs.mkdirSync(path.join(dst, 'lib'), { recursive: true });
const files = {};
const sha = (b) => createHash('sha256').update(b).digest('hex');
for (const l of LIBS) {
  const b = fs.readFileSync(path.join(src, 'lib', `${l}.mjs`));
  fs.writeFileSync(path.join(dst, 'lib', `${l}.mjs`), b);
  files[`lib/${l}.mjs`] = sha(b);
}
const schemaDir = path.join(src, 'schemas/v1');
const schemas = fs.readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json')).sort().map((f) => {
  const b = fs.readFileSync(path.join(schemaDir, f));
  files[`schemas/v1/${f}`] = sha(b);
  return JSON.parse(b.toString('utf8'));
});
fs.cpSync(schemaDir, path.join(dst, 'schemas/v1'), { recursive: true });
fs.writeFileSync(path.join(dst, 'schemas.mjs'), `// generated by scripts/vendor-assets-contract.mjs — do not edit\nexport const SCHEMAS = ${JSON.stringify(schemas)};\n`);
fs.mkdirSync(path.join(dst, 'config'), { recursive: true });
for (const f of ['sticker-assets.json', 'CONTRACT.md']) {
  const b = fs.readFileSync(path.join(src, f));
  fs.writeFileSync(path.join(dst, f), b);
  files[f] = sha(b);
}
for (const f of fs.readdirSync(path.join(src, 'config')).filter((x) => x.endsWith('.json'))) {
  const b = fs.readFileSync(path.join(src, 'config', f));
  fs.writeFileSync(path.join(dst, 'config', f), b);
  files[`config/${f}`] = sha(b);
}
const fixture = path.join(src, 'fixtures/sample-repo');
if (fs.existsSync(fixture)) fs.cpSync(fixture, path.join(dst, 'fixtures/sample-repo'), { recursive: true });
let commit = null;
let dirty = null;
try {
  commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  dirty = execFileSync('git', ['-C', src, 'status', '--porcelain'], { encoding: 'utf8' }).trim().length > 0;
} catch {}
fs.writeFileSync(path.join(dst, 'VERSION.json'), JSON.stringify({ source: 'sticker-assets', commit, dirty, vendoredAt: new Date().toISOString(), files }, null, 2) + '\n');
console.log(`vendored A contract from ${src} @ ${commit}${dirty ? ' (dirty working tree)' : ''}`);
